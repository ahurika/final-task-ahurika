"""
Deterministic Mock Embedding Provider for Offline Testing
Location: src/embeddings/mock_provider.py

Generates reproducible, deterministic pseudo-random unit vectors for offline
testing, ingestion verification, and pipeline validation without making external
API calls.

WARNING:
Mock vectors generated by this provider ARE NOT semantic embeddings. They are
cryptographically derived synthetic unit vectors designed solely to verify
pipeline wiring, database vector persistence, dimensions, and caching contracts.
They DO NOT reflect semantic textual similarity or retrieval relevance.
"""

import hashlib
import math
import random
import unicodedata
from typing import List, Optional

from src.embeddings.base import (
    BaseEmbeddingProvider,
    EmbeddingDimensionError,
    EmbeddingValueError,
    validate_text_input,
    validate_vector,
)

# Bounds consistent with pgvector HNSW limits from src/db/schema.py
MIN_VECTOR_DIMENSION = 1
MAX_HNSW_VECTOR_DIMENSION = 2000


class DeterministicMockEmbeddingProvider(BaseEmbeddingProvider):
    """
    Deterministic offline embedding provider.
    
    Given identical input text, model_name, dimensions, and seed, this provider
    guarantees bit-for-bit identical vector outputs. Distinct inputs produce distinct
    pseudo-random vectors uniformly distributed over the unit hypersphere.
    """

    def __init__(
        self,
        model_name: str = "mock-deterministic-v1",
        dimensions: int = 768,
        seed: int = 42,
    ):
        """
        Initializes the mock provider.

        Args:
            model_name: Identifier for the mock model (e.g. 'mock-deterministic-v1').
            dimensions: Output vector length (1 to 2000). Default: 768.
            seed: Master integer seed for pseudo-random derivation.
        """
        if not isinstance(model_name, str) or not model_name.strip():
            raise EmbeddingValueError("model_name must be a non-empty string.")

        if isinstance(dimensions, bool) or not isinstance(dimensions, int):
            raise EmbeddingDimensionError(f"dimensions must be an integer, got {type(dimensions).__name__}.")

        if not (MIN_VECTOR_DIMENSION <= dimensions <= MAX_HNSW_VECTOR_DIMENSION):
            raise EmbeddingDimensionError(
                f"dimensions ({dimensions}) out of bounds. Must be between "
                f"{MIN_VECTOR_DIMENSION} and {MAX_HNSW_VECTOR_DIMENSION}."
            )

        self._model_name = model_name.strip()
        self._dimensions = dimensions
        self._seed = seed

    @property
    def model_name(self) -> str:
        return self._model_name

    @property
    def dimensions(self) -> int:
        return self._dimensions

    @property
    def seed(self) -> int:
        return self._seed

    @property
    def is_mock(self) -> bool:
        """Explicit indicator that this provider produces non-semantic mock vectors."""
        return True

    def embed_text(self, text: str) -> List[float]:
        """
        Generates a deterministic unit vector for the given text.

        1. Validates text is non-empty string.
        2. Normalizes Unicode to NFC form.
        3. Computes SHA-256 seed incorporating seed, model, dimensions, and text.
        4. Samples Gaussian distribution to produce a direction vector.
        5. Normalizes to unit length (L2 norm = 1.0).
        6. Validates dimension and finite values before returning.
        """
        validate_text_input(text)
        normalized = unicodedata.normalize("NFC", text)

        # Cryptographically derive a deterministic 64-bit seed from the exact inputs
        key = f"{self._seed}::{self._model_name}::{self._dimensions}::{normalized}".encode("utf-8")
        digest = hashlib.sha256(key).digest()
        int_seed = int.from_bytes(digest[:8], byteorder="big")

        rng = random.Random(int_seed)
        raw_components = [rng.gauss(0.0, 1.0) for _ in range(self._dimensions)]

        # Normalize to unit vector (L2 norm = 1.0) to model standard cosine embeddings
        sq_sum = sum(x * x for x in raw_components)
        norm = math.sqrt(sq_sum) if sq_sum > 0.0 else 1.0
        unit_vector = [x / norm for x in raw_components]

        # Final structural validation
        validate_vector(unit_vector, self._dimensions)
        return unit_vector

    def embed_document(self, text: str, title: Optional[str] = None) -> List[float]:
        """
        Embeds a document chunk with deterministic incorporation of title.
        """
        effective_text = f"{title.strip()}\n{text}" if title and title.strip() else text
        return self.embed_text(effective_text)

    def embed_query(self, query: str) -> List[float]:
        """
        Embeds a search query using the deterministic seed.
        """
        return self.embed_text(query)
